package org.cgse.core;

import java.math.BigInteger;
import java.util.*;

/** Ready queue for acyclic material flow, allowing tools conserved by every selected recipe. */
final class DagScheduler<K> {

    private final List<String> recipes;
    private final BigInteger[] remaining;
    private final long[] generation;
    private final ReadyQueue ready;
    private final ReadyQueue awakened;
    private final PriorityQueue<Retry> retries = new PriorityQueue<>(Comparator.comparingLong(Retry::tick));
    private final DagWakeIndex<K> consumers;
    private long wakeupVisits;
    private int unfinished;
    private int active = -1;
    private boolean preferAwakened = true;

    private DagScheduler(Map<String, BigInteger> counts, Map<String, GraphRecipe<K>> recipes, Map<String, BigInteger> accepted) {
        this.recipes = List.copyOf(counts.keySet());
        remaining = new BigInteger[counts.size()];
        ready = new ReadyQueue(counts.size());
        awakened = new ReadyQueue(counts.size());
        generation = new long[counts.size()];
        for (int i = 0; i < this.recipes.size(); i++) {
            String recipe = this.recipes.get(i);
            remaining[i] = counts.get(recipe).subtract(accepted.getOrDefault(recipe, BigInteger.ZERO));
            if (remaining[i].signum() < 0) throw new IllegalArgumentException("DAG accepted count exceeds plan");
        }
        consumers = new DagWakeIndex<>(this.recipes.stream().map(recipes::get).toList(), remaining);
        for (int i = 0; i < this.recipes.size(); i++) {
            if (remaining[i].signum() > 0) {
                unfinished++;
                enqueue(i);
            }
        }
    }

    static <K> DagScheduler<K> create(GraphPlan<K> plan, Map<String, BigInteger> accepted) {
        // Count the shared program without expanding repeats. A long-sized order
        // can require more than long executions of an intermediate recipe.
        Map<String, BigInteger> counts = plan.patternTimesExact();
        List<String> steps = new ArrayList<>(counts.keySet());
        Set<K> conserved = conserved(steps.stream().map(plan.recipes()::get).toList());
        if (!conserved.containsAll(plan.seeds().keySet())) return null;
        Map<K, Integer> lastProducer = new HashMap<>();
        for (int i = 0; i < steps.size(); i++) {
            for (K output : plan.recipes().get(steps.get(i)).executionOutputs().keySet()) lastProducer.put(output, i);
        }
        for (int i = 0; i < steps.size(); i++) {
            for (K input : plan.recipes().get(steps.get(i)).inputs().keySet()) {
                // Every use returns exactly what it took. Actual owned stock
                // still gates dispatch, and all returns must arrive to finish.
                // Removing only these edges lets consumers free a full buffer
                // without imposing a serial barrier across a shared tool.
                if (conserved.contains(input)) continue;
                // No resource can be regenerated by this or any later operation.
                // Thus arbitrary ready-node dispatch cannot steal a cyclic seed.
                if (lastProducer.getOrDefault(input, -1) >= i) return null;
            }
        }
        return new DagScheduler<>(counts, plan.recipes(), accepted);
    }

    static <K> Set<K> conserved(Collection<GraphRecipe<K>> recipes) {
        Set<K> conserved = new HashSet<>(), changed = new HashSet<>();
        for (GraphRecipe<K> recipe : recipes) {
            recipe.inputs().forEach((key, input) -> {
                if (!recipe.configurationInputs().containsKey(key) && recipe.executionOutputs().getOrDefault(key, 0L).equals(input)) conserved.add(key);
                else changed.add(key);
            });
            recipe.executionOutputs().forEach((key, output) -> {
                if (!recipe.inputs().getOrDefault(key, 0L).equals(output)) changed.add(key);
            });
        }
        conserved.removeAll(changed);
        return conserved;
    }

    PlanStep.Batch poll(long tick) {
        while (!retries.isEmpty() && retries.peek().tick <= tick) {
            Retry retry = retries.remove();
            if (generation[retry.index] == retry.generation) enqueue(retry.index);
        }
        if (ready.isEmpty() && awakened.isEmpty()) {
            active = -1;
            return null;
        }
        // Actual receipts should not wait behind the initial scan of thousands
        // of known-unfunded states. Alternate lanes while both have work so a
        // busy return stream cannot starve unrelated nodes or due retries.
        boolean wake = !awakened.isEmpty() && (preferAwakened || ready.isEmpty());
        active = (wake ? awakened : ready).removeFirst();
        // Polling removes the ready notification. Subscribe again before the
        // provider call, which may synchronously return an input of this node.
        consumers.enable(active);
        preferAwakened = !wake;
        return new PlanStep.Batch(recipes.get(active), ExactAmounts.capped(remaining[active]));
    }

    void accepted(long runs) {
        if (active < 0 || runs <= 0 || BigInteger.valueOf(runs).compareTo(remaining[active]) > 0) throw new IllegalArgumentException("No prepared DAG batch");
        remaining[active] = remaining[active].subtract(BigInteger.valueOf(runs));
        if (remaining[active].signum() == 0) {
            unfinished--;
            // A synchronous return may have woken this very batch before the
            // provider returned. It must not leave a zero-run ready entry.
            ready.remove(active);
            awakened.remove(active);
            consumers.disable(active);
            generation[active]++;
        }
        else enqueue(active);
    }

    void retry(long tick) {
        if (active >= 0 && remaining[active].signum() > 0) {
            ready.remove(active);
            awakened.remove(active);
            consumers.enable(active);
            retries.add(new Retry(active, tick, ++generation[active]));
        }
    }

    void resourceChanged(K key) {
        for (int index; (index = consumers.first(key)) >= 0; ) {
            wakeupVisits++;
            // One ready notification already covers every input event for
            // this node. Remove all its subscriptions until it is polled.
            consumers.disable(index);
            ready.remove(index);
            generation[index]++;
            awakened.addLast(index);
        }
    }

    private void enqueue(int index) {
        if (remaining[index].signum() <= 0 || ready.contains(index) || awakened.contains(index)) return;
        generation[index]++;
        consumers.enable(index);
        ready.addLast(index);
    }

    long wakeupVisits() { return wakeupVisits; }
    long wakeupIndexWordVisits() { return consumers.wordVisits(); }

    boolean finished() {
        return unfinished == 0;
    }

    private record Retry(int index, long tick, long generation) {}

    /** Intrusive indexed FIFO: O(1) dedup/removal/promotion, no stale queue nodes. */
    private static final class ReadyQueue {
        private final int[] previous, next;
        private int head = -1, tail = -1;

        ReadyQueue(int size) {
            previous = new int[size];
            next = new int[size];
            Arrays.fill(previous, -2);
        }

        boolean isEmpty() { return head < 0; }
        boolean contains(int index) { return previous[index] != -2; }

        void addLast(int index) {
            if (contains(index)) return;
            previous[index] = tail;
            next[index] = -1;
            if (tail < 0) head = index;
            else next[tail] = index;
            tail = index;
        }

        int removeFirst() {
            int index = head;
            remove(index);
            return index;
        }

        void remove(int index) {
            if (!contains(index)) return;
            int before = previous[index], after = next[index];
            if (before < 0) head = after;
            else next[before] = after;
            if (after < 0) tail = before;
            else previous[after] = before;
            previous[index] = -2;
        }
    }
}
